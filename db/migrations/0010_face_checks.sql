-- Face-verification pilot, phase 2: the check pipeline.
--
--   * A face check is a REVIEW SIGNAL only. It never creates, changes, invalidates or restores an
--     attendance record; the QR check-in path, its unique constraint and its time are untouched.
--   * No raw frame is stored. Frames are used once, in memory, by the verifier; only the outcome, the
--     model version, and (briefly) a liveness label and match score are kept.
--   * The outcome is kept with the attendance; the liveness and score detail live in a separate table
--     that retention deletes after FACE_DETAIL_RETENTION_DAYS, without touching the outcome.

CREATE TYPE face_check_outcome AS ENUM (
  'VERIFIED',          -- live, and matched the enrolled template
  'FAILED',            -- live, but did not match
  'LIVENESS_REJECTED', -- not a live capture
  'EXEMPT',            -- no active consent or enrollment: fall back to an in-person check
  'EXPIRED',           -- the challenge was not completed in time
  'UNAVAILABLE'        -- the verifier was down; fall back to normal random sampling
);

-- A single-use challenge, issued after a check-in and bound to the attendance, the device claim that
-- made the check-in, and the QR token id it used. The content (e.g. a short head-movement sequence)
-- is generated by the server.
CREATE TABLE face_check_challenges (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  attendance_id uuid NOT NULL,
  course_id     uuid NOT NULL,
  session_id    uuid NOT NULL,
  student_id    uuid NOT NULL REFERENCES users (id),
  device_hash   bytea,
  token_jti     text,
  content       jsonb NOT NULL,
  expires_at    timestamptz NOT NULL,
  used_at       timestamptz,
  created_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT face_check_challenges_attendance_fk FOREIGN KEY (attendance_id, course_id)
    REFERENCES attendance_records (id, course_id),
  CONSTRAINT face_check_challenges_session_fk FOREIGN KEY (session_id, course_id)
    REFERENCES class_sessions (id, course_id)
);
CREATE INDEX face_check_challenges_attendance_idx ON face_check_challenges (attendance_id);
CREATE INDEX face_check_challenges_expiry_idx ON face_check_challenges (expires_at);

-- Append-only: one row per attempt. The current state of an attendance's face check is the row with
-- the highest attempt_number. The outcome is kept to the attendance retention window.
CREATE TABLE attendance_face_check_events (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  attendance_id  uuid NOT NULL,
  course_id      uuid NOT NULL,
  session_id     uuid NOT NULL,
  student_id     uuid NOT NULL REFERENCES users (id),
  challenge_id   uuid REFERENCES face_check_challenges (id),
  attempt_number integer NOT NULL CHECK (attempt_number >= 1),
  outcome        face_check_outcome NOT NULL,
  model_version  text NOT NULL,
  at             timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT face_check_events_attendance_fk FOREIGN KEY (attendance_id, course_id)
    REFERENCES attendance_records (id, course_id),
  CONSTRAINT face_check_events_attempt_key UNIQUE (attendance_id, attempt_number)
);
CREATE INDEX face_check_events_attendance_idx ON attendance_face_check_events (attendance_id, attempt_number DESC);
CREATE INDEX face_check_events_student_idx ON attendance_face_check_events (student_id);
CREATE INDEX face_check_events_session_idx ON attendance_face_check_events (session_id);

-- Liveness label and match score, kept only FACE_DETAIL_RETENTION_DAYS. Retention deletes these rows
-- wholesale by age; the outcome in attendance_face_check_events is left in place.
CREATE TABLE face_check_details (
  event_id    uuid PRIMARY KEY REFERENCES attendance_face_check_events (id),
  liveness    text CHECK (liveness IN ('PASS', 'FAIL')),
  match_score numeric(6, 4),
  at          timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX face_check_details_age_idx ON face_check_details (at);
